const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
(async()=>{
  const {parseHTML}=await import('./vendor/linkedom.mjs');
  const root=path.join(__dirname,'../dist');
  const {document}=parseHTML(fs.readFileSync(path.join(root,'index.html'),'utf8'));
  const handlers={};
  const ctx={document,location:{hash:''},Intl,console,setTimeout:()=>0,matchMedia:()=>({matches:true}),scrollTo:()=>{},addEventListener:(name,fn)=>{handlers[name]=fn;}};
  ctx.window=ctx;
  vm.createContext(ctx);
  for(const file of ['model.js','banking.js','app.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx,{filename:file});
  const q=selector=>document.querySelector(selector);
  const go=page=>{ctx.location.hash='#'+page;handlers.hashchange();};
  const click=selector=>q(selector).onclick();
  const retired=/supply.chain|shipment|inventory|Rotterdam|Meridian|ORD-104|reallocat|\b(?:ERP|WMS|TMS)\b/i;
  const routes=['banking','overview','explorer','decisions','architecture','study','sources'];
  assert.equal(document.querySelectorAll('nav a').length,7);
  for(const [i,page] of routes.entries()){
    go(page);
    assert.doesNotMatch(q('#page').textContent,retired,page);
    assert.match(document.title,/banking|payment|evidence/i);
    assert.equal(q('nav a[aria-current="page"]').dataset.page,page);
    assert.match(q('.eyebrow').textContent,new RegExp('CHAPTER 0'+(i+1)));
  }
  go('explorer');
  assert.equal(document.querySelectorAll('[data-bank-inspect]').length,16);
  click('[data-mode="schema"]');
  assert.match(q('#bank-inspector').textContent,/SCHEMA DEFINITION/);
  click('[data-bank-inspect="Consent"]');
  assert.match(q('#bank-inspector').textContent,/expiresAt/);
  assert.match(q('#bank-inspector').textContent,/timestamp/);
  q('#search').oninput({target:{value:'zzzz'}});
  assert.match(q('#objects').textContent,/No matching banking/);
  click('[data-mode="instances"]');
  q('#search').oninput({target:{value:'BILL-301'}});
  assert.equal(document.querySelectorAll('[data-bank-inspect]').length,1);
  click('[data-bank-inspect="Bill"]');
  assert.match(q('#bank-inspector').textContent,/BILL-301/);
  let prevented=false;
  q('[data-bank-node="Account"]').onkeydown({key:'Enter',preventDefault:()=>{prevented=true;}});
  assert.equal(prevented,true);
  assert.match(q('#bank-inspector').textContent,/ACC-101/);
  go('decisions');
  click('#bank-propose');
  q('#bank-consent').checked=true;
  q('#bank-consent').onchange({target:q('#bank-consent')});
  click('#bank-submit');
  assert.match(q('#bank-state').textContent,/Queued/);
  go('overview');click('[data-bank-node="Account"]');
  assert.match(q('#bank-inspector').textContent,/\$1,485\.00/);
  go('explorer');click('[data-bank-inspect="Bill"]');
  assert.match(q('#bank-inspector').textContent,/Unpaid/);
  go('banking');assert.match(q('#bank-state').textContent,/Queued/);
  click('#bank-settle');
  go('explorer');click('[data-bank-inspect="Bill"]');
  assert.match(q('#bank-inspector').textContent,/Paid/);
  click('[data-bank-inspect="PaymentInstruction"]');
  assert.match(q('#bank-inspector').textContent,/Settled/);
  assert.match(q('#bank-inspector').textContent,/TXN-901/);
  go('decisions');assert.match(q('#bank-state').textContent,/Settled/);
  click('#bank-reset');
  go('overview');click('[data-bank-node="Account"]');
  assert.match(q('#bank-inspector').textContent,/\$1,600\.00/);
  go('study');
  const answers=[1,1,0,2,1,1,2,0];
  click('[data-question="0"][data-answer="0"]');
  assert.match(q('#feedback-0').textContent,/Revisit/);
  answers.forEach((answer,i)=>click('[data-question="'+i+'"][data-answer="'+answer+'"]'));
  assert.match(q('#score').textContent,/8 \/ 8/);
  go('sources');
  assert.equal(document.querySelectorAll('.source-item').length,21);
  go('study');assert.match(q('#score').textContent,/8 \/ 8/);
  click('#restart-quiz');assert.match(q('#score').textContent,/0 \/ 8/);
  go('constructor');assert.match(q('h1').textContent,/Everyday banking/);
  console.log('All seven banking chapters passed: consistent content, navigation, schema/instance inspection, all 16 types, search, keyboard activation, shared payment state, reset, eight quiz questions and 21 sources.');
})().catch(error=>{console.error(error);process.exitCode=1;});
